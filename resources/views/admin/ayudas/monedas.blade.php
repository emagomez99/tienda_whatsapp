<h6 class="ayuda-titulo">¿Para qué sirven?</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-currency-exchange"></i></span>
    <div><strong>Para comprar o vender en otra moneda.</strong><br>Por ejemplo, si un proveedor te cobra en dólares. Si todo lo manejás en pesos, no hace falta tocar nada acá.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-house"></i></span>
    <div><strong>Tu moneda es en la que cobrás.</strong><br>Se elige en Ajustes › Tienda. Es la regla con la que se miden las demás, por eso no lleva cotización.</div>
</div>

<h6 class="ayuda-titulo">La cotización</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-arrow-left-right"></i></span>
    <div><strong>Cuánto vale 1 de esa moneda en la tuya.</strong><br>Se escribe como se dice: «1 USD equivale a 1.000 ARS». La tabla <em>Equivalencias</em>, abajo de la lista, te muestra todas las cuentas hechas.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-percent"></i></span>
    <div><strong>Si la cambiás, los precios <em>Por margen</em> se actualizan solos.</strong><br>Son los productos que calculan su precio a partir de lo que te cuestan más tu ganancia. Los de <em>Precio fijo</em> no cambian.</div>
</div>

<div class="ayuda-ejemplo">
    <div class="fw-semibold mb-1">Ejemplo: un supermercado</div>
    Una gaseosa importada te cuesta 2 USD y le ganás 50 %.<br>
    Con 1 USD = 1.000 ARS → cuesta $2.000 y se vende a $3.000.<br>
    Sube a 1 USD = 1.200 ARS → cuesta $2.400 y pasa sola a $3.600.<br>
    La <em>Gaseosa Coca-Cola 1,5 L</em>, con precio fijo en pesos, queda igual.
</div>

<h6 class="ayuda-titulo">Dejar de usarla</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-toggle-off"></i></span>
    <div><strong>Apagá <em>Activa</em> o borrala.</strong><br>Las dos cosas se pueden sólo si no es tu moneda y ningún producto la usa: primero pasá esos productos a otra moneda.</div>
</div>
