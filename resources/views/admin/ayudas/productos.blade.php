<h6 class="ayuda-titulo">Cargar un producto, paso a paso</h6>
<div class="ayuda-ejemplo">
    <div class="fw-semibold">Ejemplo: Gaseosa Coca-Cola 1,5 L</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono">1</span>
    <div><strong>Lo básico.</strong><br>Nombre («Gaseosa Coca-Cola 1,5 L»), precio y cuántas tenés. Si un campo no se entiende, tocá su <i class="bi bi-question-circle"></i>.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono">2</span>
    <div><strong>Elegí su estante.</strong><br>Tocá <em>Elegir categorías</em> y marcá «Gaseosas». Aparece sola también en «Bebidas».</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono">3</span>
    <div><strong>Completá sus datos.</strong><br>Al elegir «Gaseosas» aparecen los datos que pide: Marca, Sabor, Contenido. Los que tienen <span class="text-danger">*</span> son obligatorios. Mientras escribís, te sugiere lo que ya usaste, así no queda «Arcor» en uno y «Arcorr» en otro.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono">4</span>
    <div><strong>Subí las fotos.</strong><br>La primera es la que se ve en la tienda y en Google.</div>
</div>

<div class="ayuda-ejemplo">
    <div class="fw-semibold mb-1">¿Características u «Otros datos»?</div>
    <strong>Características:</strong> datos que tienen todas las gaseosas y sirven para buscar. Sabor: Cola, Contenido: 1,5 litros.<br>
    <strong>Otros datos:</strong> algo especial de este producto. Envase: Retornable, Edición: Navidad.
</div>

<h6 class="ayuda-titulo">El listado</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-file-earmark-spreadsheet"></i></span>
    <div><strong>¿Muchos productos? Usá Excel.</strong><br>Con el botón <em>Excel</em> podés cargar o actualizar cientos de productos con una planilla, o bajar los tuyos para editarlos.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-funnel"></i></span>
    <div><strong>Buscá y filtrá.</strong><br>Por nombre, proveedor, categoría o stock. Elegí <em>Sin categoría</em> para ver los que todavía no están en ningún estante.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-check2-square"></i></span>
    <div><strong>Cambiá muchos de una vez.</strong><br>Marcá la casilla de cada producto. Abajo aparece una barra: tocá <em>Agregar categorías</em>, elegí «Gaseosas» y listo. Si marcás todos, te ofrece elegir también los de las otras páginas.</div>
</div>
