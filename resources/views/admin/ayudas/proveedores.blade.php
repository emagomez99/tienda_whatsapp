<h6 class="ayuda-titulo">¿Qué es un proveedor?</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-truck"></i></span>
    <div><strong>Es quien te vende la mercadería.</strong><br>En un supermercado: la distribuidora de Coca-Cola, la que trae los fideos, la de artículos de limpieza.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-eye-slash"></i></span>
    <div><strong>Tus clientes no lo ven.</strong><br>Es para que vos te organices: no aparece en la tienda.</div>
</div>

<h6 class="ayuda-titulo">Para qué sirve</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-box-seam"></i></span>
    <div><strong>Cada producto dice de quién es.</strong><br>Al cargar un producto elegís su proveedor. Si no compraste a nadie (lo hacés vos), creá uno con el nombre de tu negocio.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-funnel"></i></span>
    <div><strong>Encontrás rápido lo de cada uno.</strong><br>En Productos, elegí el proveedor arriba y ves sólo lo suyo. Sirve para hacerle un pedido o actualizar sus precios.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-upc"></i></span>
    <div><strong>Te arma los códigos.</strong><br>Si le ponés <em>Letras para los códigos</em> (por ejemplo COCA), al cargar un producto suyo el botón <i class="bi bi-arrow-clockwise"></i> inventa un código como COCA-482913. Es opcional.</div>
</div>

<div class="ayuda-ejemplo">
    <div class="fw-semibold mb-1">Ejemplo: un supermercado</div>
    Distribuidora Coca-Cola → letras COCA<br>
    &nbsp;&nbsp;└ Gaseosa Coca-Cola 1,5 L · código COCA-482913<br>
    Molinos (fideos) → letras MOL<br>
    &nbsp;&nbsp;└ Fideos tirabuzón 500 g · código MOL-120455
</div>

<h6 class="ayuda-titulo">Dejar de usarlo</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-toggle-off"></i></span>
    <div><strong>Apagá <em>Proveedor activo</em>.</strong><br>Ya no aparece al cargar productos nuevos, pero los que tenía siguen igual.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-trash"></i></span>
    <div><strong>Borrarlo sólo se puede si no tiene productos.</strong><br>Primero pasá sus productos a otro proveedor, o apagalo.</div>
</div>
