<h6 class="ayuda-titulo">Qué hay en cada pestaña</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-palette"></i></span>
    <div><strong>Apariencia.</strong><br>Tu logo, el nombre de la tienda, el color principal y dónde va el menú (arriba o al costado).</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-shop"></i></span>
    <div><strong>Tienda.</strong><br>Si se muestran los precios, los productos sin stock y el proveedor, y en qué moneda cobrás.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-instagram"></i></span>
    <div><strong>Redes sociales.</strong><br>Tus redes, para que aparezcan en la tienda.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-google"></i></span>
    <div><strong>SEO.</strong><br>Cómo aparece tu tienda cuando alguien la busca en Google.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-whatsapp"></i></span>
    <div><strong>Pedidos.</strong><br>El WhatsApp donde te llegan los pedidos, si se pide la dirección de envío y el mensaje que te manda el cliente.</div>
</div>

