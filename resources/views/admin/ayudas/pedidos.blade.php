<h6 class="ayuda-titulo">¿De dónde salen los pedidos?</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-shop"></i></span>
    <div><strong>De tu tienda.</strong><br>Cuando un cliente termina una compra, el pedido aparece acá como <em>Pendiente</em>, y el cliente además te lo manda por WhatsApp (al número que pusiste en Ajustes › Pedidos).</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-plus-lg"></i></span>
    <div><strong>O lo cargás vos.</strong><br>Con <em>Nuevo</em>: por ejemplo, alguien que te pidió por teléfono o vino al local. Si no querés anotar sus datos, elegí <em>Consumidor Final</em>.</div>
</div>

<h6 class="ayuda-titulo">Qué pasa con el stock</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-hourglass-split"></i></span>
    <div><strong>Pendiente: todavía no toca el stock.</strong><br>Es un pedido que llegó y falta revisar.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-check-circle"></i></span>
    <div><strong>Confirmar descuenta lo que se lleva.</strong><br>Si de algún producto no alcanza el stock, no te deja confirmar y te dice cuál falta (salvo los que se pueden pedir sin stock).</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-x-circle"></i></span>
    <div><strong>Cancelar lo devuelve.</strong><br>Si el pedido ya estaba confirmado, lo que se había descontado vuelve al stock.</div>
</div>

<div class="ayuda-ejemplo">
    <div class="fw-semibold mb-1">Ejemplo: un supermercado</div>
    Hay 10 <em>Gaseosa Coca-Cola 1,5 L</em>.<br>
    María pide 2 gaseosas y 1 paquete de fideos → queda <em>Pendiente</em> (siguen 10).<br>
    Lo confirmás → quedan 8.<br>
    María avisa que no viene y lo cancelás → vuelven a ser 10.
</div>

<h6 class="ayuda-titulo">Cambiar un pedido</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-pencil"></i></span>
    <div><strong>Abrilo y cambiá lo que haga falta.</strong><br>Podés cambiar cantidades, sacar o sumar productos mientras no esté cancelado. Si ya estaba confirmado, el stock se acomoda solo.</div>
</div>

<h6 class="ayuda-titulo">Encontrar un pedido</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-calendar3"></i></span>
    <div><strong>Al entrar ves los últimos 30 días.</strong><br>Cambiá las fechas arriba para ver otros, o buscá por nombre, celular o número (#123). Las pestañas separan pendientes, confirmados y cancelados.</div>
</div>
