<h6 class="ayuda-titulo">¿Qué es una característica?</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-ui-checks"></i></span>
    <div><strong>Es un dato que anotás de cada producto.</strong><br>La marca, el sabor, cuánto trae.</div>
</div>

<div class="ayuda-ejemplo">
    <div class="fw-semibold mb-1">Ejemplo: una gaseosa</div>
    Marca: <strong>Coca-Cola</strong><br>
    Sabor: <strong>Cola</strong><br>
    Contenido: <strong>1,5 litros</strong>
    <div class="text-muted mt-2">«Marca», «Sabor» y «Contenido» son las características. «Coca-Cola», «Cola» y «1,5 litros» son sus valores, y se escriben en cada producto.</div>
</div>

<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-search"></i></span>
    <div><strong>Sirven para que tus clientes encuentren lo que buscan.</strong><br>Por ejemplo: «gaseosas de 1,5 litros» o «todo lo de Arcor».</div>
</div>

<h6 class="ayuda-titulo">¿Quién decide qué datos se piden?</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-bookshelf"></i></span>
    <div><strong>Cada categoría.</strong><br>Una gaseosa pide sabor y contenido. Unos fideos piden el tipo (spaghetti, tirabuzón). Un detergente no pide sabor. Se configura al editar la categoría.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-globe"></i></span>
    <div><strong>O todos los productos.</strong><br>La marca la tiene cualquier producto. Editala y prendé <em>Pedirla en todos los productos</em>.</div>
</div>

<h6 class="ayuda-titulo">¿Un producto con varios?</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-tags"></i></span>
    <div><strong>Prendé <em>Un producto puede tener varios</em>.</strong><br>Un pack de gaseosas puede venir en sabor Cola y Lima. Al cargar el producto escribís cada sabor y apretás Enter: queda como una fichita. En Excel, separalos con punto y coma: <em>Cola; Lima</em>.</div>
</div>

<h6 class="ayuda-titulo">Corregir errores</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-chevron-right"></i></span>
    <div><strong>Tocá una característica para ver sus valores.</strong><br>Si alguien escribió «Arcorr», corregilo ahí y se arregla en todos los productos de una vez. Si ya existía «Arcor», te pregunta si querés juntarlos en uno solo.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-eye"></i></span>
    <div><strong>El ojito</strong> muestra u oculta el dato en la tienda. Oculto, lo ves sólo vos.</div>
</div>
