{{-- Ayuda: Historial de stock. Cada fila es una vez que cambió el stock, como el cuaderno del almacén. --}}
<h6 class="ayuda-titulo">¿Qué es esta lista?</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-journal-text"></i></span>
    <div><strong>Es el cuaderno del stock.</strong><br>Cada vez que entra o sale mercadería queda anotado: cuándo, por qué y quién. Lo más nuevo va arriba.</div>
</div>

<h6 class="ayuda-titulo">Las columnas</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-tag"></i></span>
    <div><strong>Tipo.</strong><br>Ajuste (lo cambiaste vos), Salida por pedido (confirmaste un pedido) o Devolución (cancelaste un pedido o le sacaste un producto).</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-plus-slash-minus"></i></span>
    <div><strong>Variación y stock.</strong><br>+5 son 5 que entraron, −2 son 2 que salieron. Al lado, cuántos quedaron después.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-grid-3x3-gap"></i></span>
    <div><strong>Con talles o colores.</strong><br>La fila dice de cuál fue (Talle: M) y el stock de al lado es el de ese talle, no el del producto entero.</div>
</div>

<div class="ayuda-ejemplo">
    <div class="fw-semibold mb-1">Ejemplo</div>
    Tenías 10 gaseosas. Confirmás un pedido de 2: «Salida por pedido −2, quedan 8». Si lo cancelás: «Devolución +2, quedan 10».
</div>

<h6 class="ayuda-titulo">¿Cómo cambio el stock?</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-arrow-left-right"></i></span>
    <div>Con <strong>Ajustar stock</strong>, arriba. Si el producto tiene talles o colores, el stock de cada uno se cambia en <strong>Editar</strong>, en Variantes.</div>
</div>
