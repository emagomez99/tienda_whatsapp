{{-- Ayuda: Variantes (talles, colores). Como en Tiendanube: Agregar → Talle o Color → tildar → stock de cada una. --}}
<h6 class="ayuda-titulo">¿Qué es una variante?</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-grid-3x3-gap"></i></span>
    <div><strong>Es una opción del mismo producto.</strong><br>Una remera que viene en talles S, M y L es <em>un</em> producto con 3 variantes. Cada una tiene su propio stock: podés tener 5 M y ninguna L.</div>
</div>

<h6 class="ayuda-titulo">Paso a paso</h6>
<div class="ayuda-item">
    <span class="ayuda-icono">1</span>
    <div><strong>En el producto, buscá «Variantes» y tocá <em>Agregar</em>.</strong></div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono">2</span>
    <div><strong>Elegí Talle, Color u otra cosa.</strong><br>Los talles y los colores ya vienen listos: tildá los que tenés. ¿Vendés sabores? Elegí <em>+ Nueva propiedad</em> y escribí «Sabor».</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono">3</span>
    <div><strong>Tocá <em>Crear</em> y poné cuántas hay de cada una.</strong><br>Aparece una fila por opción. Si una cuesta distinto (el XL más caro), poné su precio; si no, dejalo vacío.</div>
</div>

<div class="ayuda-ejemplo">
    <div class="fw-semibold mb-1">Ejemplo: talle y color juntos</div>
    Talle: S, M · Color: Rojo, Azul → quedan 4 filas: S Rojo, S Azul, M Rojo, M Azul. Podés usar hasta 3 propiedades.
</div>

<h6 class="ayuda-titulo">En la tienda</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-hand-index-thumb"></i></span>
    <div><strong>El cliente elige el talle con un botón.</strong><br>Si uno se terminó, aparece tachado. Al confirmar el pedido se descuenta el stock de ese talle.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-x-circle"></i></span>
    <div><strong>¿Ya no lo vendés en talles?</strong><br>Quitá las propiedades con la <i class="bi bi-x-lg"></i>. Al guardar te pregunta, y el stock de las variantes vuelve al producto.</div>
</div>
