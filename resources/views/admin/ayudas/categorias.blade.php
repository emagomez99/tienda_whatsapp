<h6 class="ayuda-titulo">¿Qué es una categoría?</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-bookshelf"></i></span>
    <div><strong>Es un estante de tu negocio.</strong><br>Como las góndolas de un supermercado: en una van las bebidas, en otra los fideos. Cada producto se pone en su estante.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-shop"></i></span>
    <div><strong>Tus clientes eligen un estante y ven sólo esos productos.</strong><br>En la tienda aparecen como botones del menú: Bebidas, Almacén, Limpieza.</div>
</div>

<div class="ayuda-ejemplo">
    <div class="fw-semibold mb-1">Ejemplo: un supermercado</div>
    Bebidas<br>
    &nbsp;&nbsp;└ Gaseosas<br>
    &nbsp;&nbsp;└ Aguas<br>
    Almacén<br>
    &nbsp;&nbsp;└ Fideos<br>
    &nbsp;&nbsp;└ Galletitas<br>
    Limpieza
    <div class="text-muted mt-2">Un estante puede tener estantes adentro. Si ponés una Coca-Cola en «Gaseosas», también aparece en «Bebidas». No hace falta marcar los dos.</div>
</div>

<h6 class="ayuda-titulo">Paso a paso</h6>
<div class="ayuda-item">
    <span class="ayuda-icono">1</span>
    <div><strong>Creá tus estantes.</strong><br>Tocá <i class="bi bi-plus-circle"></i> <em>Crear categoría</em> y escribí el nombre, por ejemplo «Bebidas». Para hacer «Gaseosas» adentro de «Bebidas», tocá el <i class="bi bi-plus-lg"></i> que aparece en la fila de «Bebidas».</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono">2</span>
    <div><strong>Decí qué hay que anotar de cada producto.</strong><br>De una gaseosa hay que saber el sabor y cuánto trae (1,5 litros). Entrá a «Gaseosas» y agregalos en <em>Datos que se piden al cargar un producto</em>. Si los marcás <span class="badge text-bg-danger">Obligatoria</span>, nadie puede guardar una gaseosa sin ese dato.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono">3</span>
    <div><strong>Poné cada producto en su estante.</strong><br>Al cargar un producto, tocá <em>Elegir categorías</em>. Si son muchos, andá a Productos, marcalos y tocá <em>Agregar categorías</em>.</div>
</div>

<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-globe"></i></span>
    <div><strong>¿Un dato que tienen todos?</strong><br>La marca la tiene una gaseosa, unos fideos y un detergente. En vez de pedirla en cada estante, pedila una vez en <em>Todos los productos</em>, arriba de todo.</div>
</div>

<h6 class="ayuda-titulo">Ordenar</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-grip-vertical"></i></span>
    <div><strong>Agarrá el <i class="bi bi-grip-vertical"></i> y arrastrá.</strong><br>Hacia arriba o abajo cambia el orden en que se ven en la tienda. Si lo soltás encima de otro estante, queda adentro de ese.</div>
</div>

<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-sort-down"></i></span>
    <div><strong>¿Qué productos se ven primero en un estante?</strong><br>Entrá a la categoría y elegí en <em>Orden de los productos</em>: por nombre, los más nuevos, el más barato o el más caro. Con <em>Elijo cuáles van primero</em> ponés adelante los que quieras, como en la punta de la góndola: por ejemplo, las ofertas.</div>
</div>

<h6 class="ayuda-titulo">Estantes vacíos, ocultos y borrados</h6>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-inbox"></i></span>
    <div><strong>Un estante sin productos no aparece en el menú de la tienda.</strong><br>Así tus clientes nunca entran a un estante vacío. Aparece solo cuando le cargás el primer producto.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-eye-slash"></i></span>
    <div><strong>Ocultar:</strong> tus clientes dejan de ver ese estante (y los de adentro). Los productos no desaparecen: se siguen encontrando con el buscador.</div>
</div>
<div class="ayuda-item">
    <span class="ayuda-icono"><i class="bi bi-trash"></i></span>
    <div><strong>Borrar:</strong> se borra el estante, no los productos. Quedan sin categoría y los podés poner en otro.</div>
</div>
<div class="small text-muted"><i class="bi bi-three-dots"></i> En cada fila, los tres puntitos tienen todas las opciones: editar, ocultar, subir, bajar y borrar.</div>
